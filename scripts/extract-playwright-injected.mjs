// Vendor Playwright's injected script (Apache-2.0) from playwright-core's bundle.
// The page-side engine opencli-mcp relies on: selector engines (role/text/label/testid/css/xpath),
// element states, fill/select helpers, hit-target checks, selector generation and aria snapshots.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, resolve } from 'node:path';

const require = createRequire(import.meta.url);
const pkg = require('playwright-core/package.json');
const bundle = readFileSync(resolve(dirname(require.resolve('playwright-core/package.json')), 'lib/coreBundle.js'), 'utf8');
const marker = "packages/playwright-core/src/generated/injectedScriptSource.ts";
const at = bundle.indexOf(marker);
if (at < 0) throw new Error('injectedScriptSource marker not found');
const assign = bundle.indexOf("source4 = '", at);
const start = assign + 'source4 = '.length;
let i = start + 1;
while (i < bundle.length) { if (bundle[i] === '\\') { i += 2; continue; } if (bundle[i] === "'") break; i++; }
const literal = bundle.slice(start, i + 1);
const source = new Function('return ' + literal)();
mkdirSync('vendor', { recursive: true });
writeFileSync('vendor/playwright-injected.js', `// Playwright injected script — Apache-2.0, https://github.com/microsoft/playwright — extracted from playwright-core ${pkg.version}\n${source}`);
const names = ['parseSelector(', 'querySelectorAll(', 'elementState(', 'checkElementStates(', 'expectHitTarget(', 'fill(', 'selectOptions(', 'focusNode(', 'retarget(', 'generateSelector(', 'ariaSnapshot(', 'aria-ref', 'getElementByRef', 'scrollIntoViewIfNeeded(', 'setInputFiles(', 'strictModeViolationError(', 'testIdAttributeName', 'stableRafCount', 'checkDeprecatedSelectorUsage', 'lastAriaSnapshot', 'ariaRef'];
for (const n of names) console.log(n.padEnd(30), source.includes(n) ? 'yes' : 'no');
const ctor = source.match(/class InjectedScript[\s\S]{0,300}?constructor\(([^)]*)\)/);
console.log('ctor:', ctor && ctor[1]);
// how the server instantiates it
let idx = bundle.indexOf('InjectedScript())(');
console.log('instantiation:', JSON.stringify(bundle.slice(idx - 400, idx + 200).replace(/\s+/g, ' ')));
console.log('bytes', source.length);
// Also emit the source as a module both the host (tsc) and the extension (esbuild) import.
writeFileSync('src/shared/injected-source.ts', `// GENERATED by scripts/extract-playwright-injected.mjs — do not edit.\n// Playwright injected script, Apache-2.0 (https://github.com/microsoft/playwright), from playwright-core ${pkg.version}.\nexport const INJECTED_SOURCE: string = ${JSON.stringify(source)};\nexport const INJECTED_VERSION = ${JSON.stringify(pkg.version)};\n`);
console.log('wrote src/shared/injected-source.ts');
