/**
 * tools.define / tools.compile — freeze an explored flow into a first-class adapter.
 * A defined tool is just an adapter file in the USER SOURCE (~/.opencli-mcp/adapters/<site>/<name>.js): the exact same
 * shape and loader as a built-in adapter, only in a different source directory. There is no separate registry.
 */
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { createRequire } from 'node:module';
import { USER_ADAPTERS_DIR } from '../lib/sources.js';
import type { TraceEvent, NetworkEvidence } from '../runtime/trace.js';

import type { Arg } from '@opencli-mcp/adapter-sdk';
export type { Arg } from '@opencli-mcp/adapter-sdk';

export interface ToolDefinition {
  site: string;
  name: string;
  description: string;
  access: 'read' | 'write';
  /** needs a logged-in page (default: inferred from whether the body uses tab/sites/recon). */
  browser?: boolean;
  domain?: string;
  args?: Arg[];
  /** JS source of the adapter body: `async ({ tab, args, sites, recon }) => …` */
  func: string;
}

const NAME_RE = /^[a-z0-9][a-z0-9-]{0,63}$/;

export function validateDefinition(def: ToolDefinition): void {
  if (!NAME_RE.test(def.site) || !NAME_RE.test(def.name)) throw Object.assign(new Error('site and name must match /^[a-z0-9][a-z0-9-]{0,63}$/'), { code: 'invalid_definition' });
  if (!def.description) throw Object.assign(new Error('description is required'), { code: 'invalid_definition' });
  if (def.access !== 'read' && def.access !== 'write') throw Object.assign(new Error("access must be 'read' or 'write'"), { code: 'invalid_definition' });
  if (!def.func) throw Object.assign(new Error('provide `func` source (async ({ tab, args }) => …)'), { code: 'invalid_definition' });
  for (const a of def.args ?? []) if (!/^[a-z][a-z0-9_]*$/.test(a.name)) throw Object.assign(new Error(`arg name ${JSON.stringify(a.name)} must be snake_case`), { code: 'invalid_definition' });
  if (!/^\s*(async\s*)?(\(|[A-Za-z_$])/.test(def.func)) throw Object.assign(new Error('func must be a function expression such as `async ({ tab, args }) => { … }`'), { code: 'invalid_definition' });
  try { new Function(`return (${def.func});`); } catch (err) { throw Object.assign(new Error(`func does not parse: ${(err as Error).message}`), { code: 'invalid_definition' }); }
}

/** Ensure the user source dir exists and can resolve `@opencli-mcp/adapter-sdk` (a symlink, so a dropped-in file just works). */
export function ensureUserSource(): string {
  fs.mkdirSync(USER_ADAPTERS_DIR, { recursive: true });
  const home = path.dirname(USER_ADAPTERS_DIR); // ~/.opencli-mcp
  const nmScope = path.join(home, 'node_modules', '@opencli-mcp');
  fs.mkdirSync(nmScope, { recursive: true });
  const link = path.join(nmScope, 'adapter-sdk');
  try {
    const sdkDir = path.dirname(createRequire(import.meta.url).resolve('@opencli-mcp/adapter-sdk'));
    const current = fs.existsSync(link) ? fs.realpathSync(link) : null;
    if (current !== fs.realpathSync(sdkDir)) { try { fs.rmSync(link, { recursive: true, force: true }); } catch { /* ignore */ } fs.symlinkSync(sdkDir, link, 'dir'); }
  } catch { /* best effort; a globally-installed sdk also resolves */ }
  const pkg = path.join(home, 'package.json');
  if (!fs.existsSync(pkg)) fs.writeFileSync(pkg, JSON.stringify({ name: 'opencli-mcp-user-adapters', private: true, type: 'module' }, null, 2));
  return USER_ADAPTERS_DIR;
}

export function renderAdapterModule(def: ToolDefinition): string {
  // browser:false lets the adapter run without provisioning a page. Infer it from the body: a func that never touches
  // tab/sites/recon is a pure call and needs no browser.
  const browser = def.browser ?? /\b(tab|sites|recon)\b/.test(def.func);
  return [
    `// Generated by opencli-mcp tools.define on ${new Date().toISOString()}`,
    `import { defineAdapter } from '@opencli-mcp/adapter-sdk';`,
    ``,
    `export default defineAdapter({`,
    `  description: ${JSON.stringify(def.description)},`,
    `  access: ${JSON.stringify(def.access)},`,
    browser ? null : `  browser: false,`,
    def.domain ? `  domain: ${JSON.stringify(def.domain)},` : null,
    `  args: ${JSON.stringify(def.args ?? [], null, 2).replace(/\n/g, '\n  ')},`,
    `  run: ${def.func.trim()},`,
    `});`,
    ``,
  ].filter((l): l is string => l !== null).join('\n');
}

export async function saveTool(def: ToolDefinition): Promise<{ file: string; site: string; name: string }> {
  validateDefinition(def);
  const dir = path.join(ensureUserSource(), def.site);
  fs.mkdirSync(dir, { recursive: true });
  const file = path.join(dir, `${def.name}.js`);
  fs.writeFileSync(file, renderAdapterModule(def));
  await import(`${pathToFileURL(file).href}?t=${Date.now()}`); // load once now to surface a bad descriptor immediately
  return { file, site: def.site, name: def.name };
}

export function deleteTool(site: string, name: string): boolean {
  const file = path.join(USER_ADAPTERS_DIR, site, `${name}.js`);
  if (!fs.existsSync(file)) return false;
  fs.rmSync(file);
  return true;
}

export function listDefinedTools(): Array<{ site: string; name: string; file: string }> {
  if (!fs.existsSync(USER_ADAPTERS_DIR)) return [];
  const out: Array<{ site: string; name: string; file: string }> = [];
  for (const site of fs.readdirSync(USER_ADAPTERS_DIR)) {
    const d = path.join(USER_ADAPTERS_DIR, site);
    try { if (!fs.statSync(d).isDirectory()) continue; } catch { continue; }
    for (const f of fs.readdirSync(d)) if (f.endsWith('.js') && !f.startsWith('_')) out.push({ site, name: f.replace(/\.js$/, ''), file: path.join(d, f) });
  }
  return out;
}


/**
 * Compile a recorded session trace into a tool draft.
 * Network-first: if the trace captured a JSON endpoint on the site, the tool fetches it through the
 * page (cookies included). Otherwise the UI steps (goto/act/observe) become an explicit function.
 * Values equal to an input are replaced by `args.<input>`.
 */
/** `mode` is the agent's explicit declaration of where the sample may be replaced: 'exact' (default) only whole literals equal to the sample; 'within' also inside longer literals (typed values, expectation texts/urls). */
export type CompileInput = string | { sample: string; description?: string; type?: 'string' | 'int' | 'number' | 'boolean'; required?: boolean; mode?: 'exact' | 'within' };

/**
 * Compile a recorded session trace into a tool draft.
 * Network-first: if the trace captured a JSON endpoint on the site, the tool fetches it through the page (cookies
 * included). Otherwise the UI steps become an explicit function on the same engine the agent used: `tab.act` with the
 * replay selector recorded at act time, `tab.expect` checkpoints where the agent asserted the page, and a structured
 * failure (`step`, `label`, `state`) when a step fails. Inputs are explicit: only exact occurrences of a declared
 * sample value become `args.<name>`.
 */
function hostOf(url: string): string | undefined { try { return new URL(url).hostname.replace(/^www\./, ''); } catch { return undefined; } }

/** Cookie names a csrf/xsrf-family header is commonly mirrored from — so a frozen tool can re-read the token at replay. */
function csrfCookieCandidates(header: string): string[] {
  return /csrf|xsrf|ct0/i.test(header) ? ['ct0', 'csrftoken', 'csrf-token', 'XSRF-TOKEN', 'xsrf-token', '_csrf'] : [];
}
const NOISE = /(googletagmanager|google-analytics|doubleclick|facebook\.net|hotjar|sentry|segment\.com|intercom|crazyegg|clarity\.ms|cloudflareinsights|hcaptcha|recaptcha|amazon-adsystem|newrelic|datadoghq|\/collect\b|\/beacon\b|\/telemetry\b|\/analytics\b|\/log\b)/i;
/** Words worth matching: what the agent saw (observe state) or extracted (evaluate result) — long enough to be specific. */
function evidenceTokens(trace: TraceEvent[]): Set<string> {
  const texts: string[] = [];
  for (const e of trace) {
    if (e.kind === 'evaluate' && e.result) texts.push(e.result);
    if (e.kind === 'observe' && e.sample) texts.push(e.sample.replace(/\[ref=e\d+\]/g, ''));
  }
  const out = new Set<string>();
  for (const t of texts.slice(-4)) for (const w of t.match(/[\p{L}\p{N}][\p{L}\p{N}'’.-]{3,}/gu) ?? []) if (!/^(true|false|null|undefined|button|link|heading|text|list|listitem|navigation|generic|main|banner|contentinfo|complementary|region|article|image|img|textbox|combobox|checkbox|https?)$/i.test(w)) out.add(w.toLowerCase());
  return out;
}
/** The captured JSON response that carries the data the agent ended up with; else the largest same-site JSON response. */
function pickEndpoint(net: NetworkEvidence[], tokens: Set<string>, host: string | undefined): { endpoint: NetworkEvidence; matched: number; byDefault: boolean } | null {
  const cands = net.filter((e) => /json|graphql|x-component/i.test(e.contentType ?? '') && (e.status ?? 200) < 400 && (e.resourceType === undefined || e.resourceType === 'XHR' || e.resourceType === 'Fetch') && !NOISE.test(e.url) && (!host || (hostOf(e.url) ?? '').endsWith(host)));
  if (!cands.length) return null;
  let best: { endpoint: typeof cands[number]; matched: number } | null = null;
  for (const c of cands) {
    if (!c.responseSample || !tokens.size) continue;
    const hay = c.responseSample.toLowerCase();
    let matched = 0; for (const t of tokens) if (hay.includes(t)) matched++;
    if (matched && (!best || matched > best.matched || (matched === best.matched && (c.bodyBytes ?? 0) > (best.endpoint.bodyBytes ?? 0)))) best = { endpoint: c, matched };
  }
  if (best) return { ...best, byDefault: false };
  const largest = [...cands].sort((a, b) => (b.bodyBytes ?? 0) - (a.bodyBytes ?? 0))[0];
  return { endpoint: largest, matched: 0, byDefault: true };
}
/** URL literal with query values equal to an input sample replaced by the (encoded) argument. */
function urlLit(url: string, inputs: Array<{ name: string; sample: string; mode: 'exact' | 'within' }>, lit: (v: string) => string): string {
  try {
    const u = new URL(url); let touched = false;
    for (const [k, v] of [...u.searchParams]) for (const i of inputs) if (i.sample && (v === i.sample || (i.mode === 'within' && v.includes(i.sample)))) { u.searchParams.set(k, `__ARG_${i.name}__${v === i.sample ? '' : v.split(i.sample).join(`__ARG_${i.name}__`)}`); touched = true; }
    if (!touched) return lit(url);
    const s = u.toString().replace(/__ARG_([a-zA-Z_$][\w$]*)__/g, (_m, n: string) => `\${encodeURIComponent(args.${n})}`);
    return '`' + s.replace(/`/g, '\\`') + '`';
  } catch { return lit(url); }
}
/**
 * Body literal: a JSON body is regenerated as a JS object where each string value is emitted safely (a JSON literal, or
 * a parameterized expression when it contains a declared sample); a form body becomes `new URLSearchParams({...}).toString()`
 * with the same per-value emitter. `emit` is the compile-local safe string emitter, so no page data can break the source.
 */
function bodyLit(post: string, contentType: string | undefined, emit: (v: string) => string): string {
  try {
    const json = JSON.parse(post) as unknown;
    const gen = (v: unknown): string => {
      if (typeof v === 'string') return emit(v);
      if (Array.isArray(v)) return `[${v.map(gen).join(',')}]`;
      if (v && typeof v === 'object') return `{${Object.entries(v as Record<string, unknown>).map(([k, x]) => `${JSON.stringify(k)}:${gen(x)}`).join(',')}}`;
      return JSON.stringify(v);
    };
    const src = gen(json);
    return `JSON.stringify(${src})`;
  } catch { /* not JSON */ }
  if (/x-www-form-urlencoded/i.test(contentType ?? '')) {
    const p = new URLSearchParams(post);
    const pairs = [...p].map(([k, v]) => `${JSON.stringify(k)}: ${emit(v)}`);
    if (pairs.length) return `new URLSearchParams({ ${pairs.join(', ')} }).toString()`;
  }
  return emit(post);
}
export function compileFromTrace(trace: TraceEvent[], net: NetworkEvidence[], opts: { site: string; name: string; description: string; access?: 'read' | 'write'; inputs?: Record<string, CompileInput>; domain?: string }): ToolDefinition & { warnings?: string[] } {
  const inputs = Object.entries(opts.inputs ?? {}).map(([name, v]) => (typeof v === 'string' ? { name, sample: v, type: 'string' as const, required: true, mode: 'exact' as const } : { name, sample: v.sample, type: v.type ?? 'string', required: v.required ?? true, help: v.description, mode: v.mode ?? 'exact' as const }));
  const argDefs: Arg[] = inputs.map((i) => ({ name: i.name, type: i.type, required: i.required, help: i.help ?? `example: ${i.sample}` }));
  for (const i of inputs) if (!/^[A-Za-z_$][\w$]*$/.test(i.name)) throw Object.assign(new Error(`input name ${JSON.stringify(i.name)} must be a JavaScript identifier`), { code: 'invalid_definition' });
  // exact by default: a literal becomes an argument only when it IS the sample; 'within' inputs are the agent's explicit
  // permission to also parameterize longer literals that contain the sample (values typed, checkpoint texts and urls)
  const sub = (v: string): string => {
    for (const i of inputs) if (i.sample && v === i.sample) return `\${args.${i.name}}`;
    let out = v;
    for (const i of inputs) if (i.mode === 'within' && i.sample && out.includes(i.sample)) out = out.split(i.sample).join(`\${args.${i.name}}`);
    return out;
  };
  // Emit JS source for a possibly-parameterized string. Our own `${args.x}` interpolations (from sub) are preserved;
  // any literal backtick, backslash, or foreign `${` in the data is escaped, so the generated tool never crashes or
  // lets page data interpolate. A plain string with no arg is a JSON string literal.
  const escTpl = (s: string): string => s.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{(?!args\.[A-Za-z_$][\w$]*\})/g, '\\${');
  const lit = (v: string): string => { const s = sub(v); const whole = /^\$\{(args\.[A-Za-z_$][\w$]*)\}$/.exec(s); return whole ? whole[1] : /\$\{/.test(s) ? '`' + escTpl(s) + '`' : JSON.stringify(s); };

  const body: string[] = [];
  const warnings: string[] = [];
  const firstGoto = trace.find((e): e is Extract<TraceEvent, { kind: 'goto' }> => e.kind === 'goto');
  const best = pickEndpoint(net, evidenceTokens(trace), opts.domain ?? (firstGoto ? hostOf(firstGoto.url) : undefined));
  if (best) {
    const { endpoint: e, matched, byDefault } = best;
    if (firstGoto) body.push(`  await tab.goto(${lit(firstGoto.url)});`);
    // freeze the whole call the page made, not a guessed URL: method, the request headers that are part of the
    // contract (x-*, content-type, accept…), the body — with the declared inputs parameterized where they occurred
    const init: string[] = [];
    if (e.method && e.method !== 'GET') init.push(`method: ${JSON.stringify(e.method)}`);
    // Contract headers travel with the tool. A header whose value looks like a token or signature (long, high-entropy)
    // is computed per request/session by the page and must not be frozen — instead we replay it: csrf/xsrf-family tokens
    // are re-read from the cookie at run time; other computed values (signatures) are named in a warning, not faked in code.
    const headers: Record<string, string> = {};   // frozen contract headers
    const dynHeaders: string[] = [];               // "H": <var> resolved at replay
    const preLines: string[] = [];                 // run-time token resolutions, emitted before fetchJson
    const cookieBacked: string[] = []; const computed: string[] = [];
    for (const [k, v] of Object.entries(e.requestHeaders ?? {})) {
      if (!/^(content-type|accept|x-.*|apikey|api-key|client-id)$/i.test(k)) continue;
      const isToken = /^x-(csrf|xsrf|client-transaction|signature|sign|nonce|timestamp|token|auth|session|guest-token|ct0)/i.test(k) || (v.length >= 32 && /^[A-Za-z0-9+/=_%.-]+$/.test(v) && !/^(application|text|multipart)\//.test(v));
      if (!isToken) { headers[k] = v; continue; }
      const cookies = csrfCookieCandidates(k);
      if (cookies.length) {
        const varName = `__tok${cookieBacked.length}`;
        preLines.push(`  const ${varName} = ${cookies.map((c) => `await tab.cookie(${JSON.stringify(c)})`).join(' || ')}; // ${k}: re-read the per-request token from the cookie at replay`);
        dynHeaders.push(`${JSON.stringify(k)}: ${varName}`);
        cookieBacked.push(k);
      } else computed.push(k);
    }
    const headerEntries = [...Object.entries(headers).map(([k, val]) => `${JSON.stringify(k)}: ${JSON.stringify(val)}`), ...dynHeaders];
    if (headerEntries.length) init.push(`headers: { ${headerEntries.join(', ')} }`);
    if (cookieBacked.length) warnings.push(`header(s) ${cookieBacked.join(', ')} are re-read from the cookie at run time (tab.cookie); verify the cookie name matches this site with tab.fetchJson`);
    if (computed.length) warnings.push(`header(s) ${computed.join(', ')} are computed by the page per request (a signature/nonce/transaction id) and are NOT frozen — this endpoint will fail until you compute them at replay: call the page's own signer with tab.evaluate, or read the value from page state, and add them to the headers before tab.fetchJson. If you cannot recompute the signature, freeze this flow as DOM steps instead.`);
    if (e.postData) init.push(`body: ${bodyLit(e.postData, e.requestHeaders?.['content-type'], lit)}`);
    for (const l of preLines) body.push(l);
    body.push(`  const data = await tab.fetchJson(${urlLit(e.url, inputs, lit)}${init.length ? `, { ${init.join(', ')} }` : ''});`);
    body.push(`  return data;`);
    if (e.auth) warnings.push(`the captured request carried an Authorization header, which is not frozen (it is a credential the page computes); the tool will fail unless the endpoint also accepts the cookie session — prefer a cookie-authenticated endpoint or read the header from the page at run time`);
    if (byDefault) warnings.push(`endpoint ${e.method ?? 'GET'} ${e.url.slice(0, 120)} was chosen by size, not by matching the data you extracted (no observe/evaluate evidence found in it); verify with tab.fetchJson before defining`);
    else warnings.push(`endpoint ${e.method ?? 'GET'} ${e.url.slice(0, 120)} matched ${matched} word(s) of the data you extracted`);
  } else {
    if (net.length) warnings.push('no JSON endpoint carried the data you extracted — the tool is frozen as UI steps (DOM); read tab.network.read() and recon.discover(tab) for an API, verify it with tab.fetchJson, then compile again');
    else warnings.push('the trace has no captured requests (capture starts when a session tab is attached; adapter tabs do not capture) — the tool is frozen as UI steps (DOM)');
    // every step is wrapped so a failure names the step, carries the engine's error code/hint and the page state at that moment
    body.push(`  const step = async (n, label, fn) => { try { return await fn(); } catch (e) { const state = await tab.observe({ diff: false, viewport: true }).then((o) => o.state || '').catch(() => ''); throw Object.assign(new Error('step ' + n + ' (' + label + ') failed: ' + (e && e.message || e)), { code: (e && e.code) || 'step_failed', hint: e && e.hint, step: n, label, state: String(state).slice(0, 4000), expect: e && e.data && e.data.expect, failed: e && e.data && e.data.failed }); } };`);
    let n = 0;
    const push = (label: string, call: string) => { n += 1; body.push(`  await step(${n}, ${JSON.stringify(label)}, () => ${call});`); };
    for (const e of trace) {
      if (e.kind === 'goto') push(`goto ${e.url.slice(0, 60)}`, `tab.goto(${lit(e.url)})`);
      else if (e.kind === 'act') {
        if (!e.ok) continue;
        const spec = (e.targetSpec ?? {}) as Record<string, unknown>;
        const { frame, ...loc } = spec;
        // freeze the intent the agent expressed (role/name, label, text, testid, a selector it chose, within), not the element the
        // engine happened to resolve it to: intent survives a redesign, the resolved selector does not. Only a one-time ref or
        // a point has no intent to keep — then the engine's replay selector is frozen and the tool is flagged for review.
        const intent = ['role', 'name', 'label', 'text', 'testid', 'selector', 'within'].some((k) => k in loc);
        const target: Record<string, unknown> = intent ? { ...loc } : e.targetSelector ? { selector: e.targetSelector } : { ...loc };
        if (frame !== undefined) target.frame = frame;
        const structural = (s: unknown) => typeof s === 'string' && !s.startsWith('internal:') && !/^#[\w-]+$|\[data-testid=|\[data-[\w-]+=|^aria-ref=/.test(s) && !s.includes(' >> internal:');
        if (!intent) {
          const why = typeof loc.ref === 'string' ? `aria ref ${loc.ref} (one-time)` : 'a viewport point';
          warnings.push(`step ${n + 1}: acted on ${why}; frozen as the engine's replay selector ${JSON.stringify(e.targetSelector ?? null)} — replace with a stable locator (testid, role+name, label, or a selector scoped by within)`);
          body.push(`  // REVIEW: acted on ${why} — the replay selector below is what the engine resolved at exploration time, not an intent`);
        } else if (structural(loc.selector)) warnings.push(`step ${n + 1}: selector ${JSON.stringify(loc.selector)} is structural css; it breaks on a redesign — prefer testid, role+name or label`);
        const valued = ['fill', 'type', 'press', 'select'].includes(e.action) && e.value !== undefined;
        push(`${e.action} ${e.target}`.slice(0, 80), `tab.act({ action: ${JSON.stringify(e.action)}, target: ${JSON.stringify(target)}${valued ? `, value: ${lit(String(e.value))}` : ''} })`);
      } else if (e.kind === 'expect') {
        if (!e.ok) continue;
        const what = Object.fromEntries(Object.entries(e.what).map(([k, v]) => [k, typeof v === 'string' ? sub(v) : v]));
        const parameterized = Object.entries(what).filter(([, v]) => typeof v === 'string' && v.includes('${args.')).map(([k]) => k);
        if (parameterized.length) body.push(`  // checkpoint ${parameterized.join('/')} follows the input (declared mode "within"); it checks the page reflects the argument, not a fixed value`);
        const literal = JSON.stringify(what).replace(/"\$\{args\.([a-zA-Z_$][\w$]*)\}"/g, 'args.$1').replace(/"([^"]*\$\{args\.[^"]*)"/g, (_m, inner: string) => '`' + inner.replace(/`/g, '\\`') + '`');
        push(`expect ${Object.keys(e.what).join(',')}`, `tab.expect(${literal})`);
      } else if (e.kind === 'observe') body.push(`  // observed: ${e.mode}${e.summary ? ' — ' + e.summary.slice(0, 80) : ''}`);
    }
    body.push(`  return await tab.observe({ diff: false });`);
  }
  const func = `async ({ tab, args }) => {\n${body.join('\n')}\n}`;
  return { site: opts.site, name: opts.name, description: opts.description, access: opts.access ?? 'read', domain: opts.domain, args: argDefs, func, ...(warnings.length && { warnings }) };
}

